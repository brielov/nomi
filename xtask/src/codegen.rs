//! `cargo xtask codegen`: the typed syntax views in
//! `crates/syntax/src/ast/generated.rs`, generated from `elm.ungram`.
//!
//! A rule that only chooses between nodes becomes an enum; every other
//! rule becomes a struct over its node kind, with accessors:
//! - a node that appears once gives `name()`, and one that repeats gives
//!   `names()` over every child of that type;
//! - labeled nodes of one type are told apart by the token next to them
//!   (`'then' then_branch:Expr` is the node right after `then`, `None` if
//!   the parser put a Missing node there), or else by position;
//! - a token outside any alternative gives `name_token()`, its first
//!   occurrence.
//!
//! Token kinds come from the `syntax_kinds!` table in `kind.rs`, not from
//! the crate itself, so a stale or broken output can always be rebuilt.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::Write as _;
use std::path::Path;
use std::process::{Command, Stdio};

use anyhow::{Context, Result, bail, ensure};
use ungrammar::{Grammar, Node, Rule};

const GRAMMAR: &str = "crates/syntax/elm.ungram";
const KINDS: &str = "crates/syntax/src/kind.rs";
const OUTPUT: &str = "crates/syntax/src/ast/generated.rs";

/// Writes the views, or with `check` fails if the file on disk differs.
pub fn run(root: &Path, check: bool) -> Result<()> {
    let grammar: Grammar = std::fs::read_to_string(root.join(GRAMMAR))
        .context("reading elm.ungram")?
        .parse()
        .map_err(|e| anyhow::anyhow!("parsing elm.ungram: {e}"))?;
    let tokens = token_kinds(&std::fs::read_to_string(root.join(KINDS))?)?;
    let code = format(root, &generate(&grammar, &tokens)?)?;
    let path = root.join(OUTPUT);
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    if current == code {
        return Ok(());
    }
    if check {
        bail!("{OUTPUT} is stale; run `cargo xtask codegen`");
    }
    std::fs::write(&path, code).with_context(|| format!("writing {OUTPUT}"))?;
    eprintln!("updated {OUTPUT}");
    Ok(())
}

/// Maps each ungram token name (`"("`, `"lower_ident"`) to its kind.
fn token_kinds(source: &str) -> Result<BTreeMap<String, String>> {
    let table = source
        .split_once("syntax_kinds! {")
        .and_then(|(_, rest)| rest.split_once("nodes {"))
        .map(|(tokens, _)| tokens)
        .context("kind.rs has no syntax_kinds! table")?;
    let mut kinds = BTreeMap::new();
    for line in table.lines() {
        let Some((kind, text)) = line.trim().split_once(" = \"") else {
            continue;
        };
        let text = text
            .strip_suffix("\",")
            .with_context(|| format!("unexpected kind.rs line {line:?}"))?
            .replace("\\\\", "\\");
        kinds.insert(text, kind.to_string());
    }
    Ok(kinds)
}

fn generate(grammar: &Grammar, tokens: &BTreeMap<String, String>) -> Result<String> {
    let mut out = String::from(
        "// @generated by `cargo xtask codegen` from `elm.ungram`. Do not edit.\n\n\
         use super::{AstChildren, AstNode, support};\n\
         use crate::{SyntaxKind, SyntaxNode, SyntaxToken};\n",
    );
    let mut structs = Vec::new();
    for node in grammar.iter() {
        let data = &grammar[node];
        match enum_variants(grammar, &data.rule) {
            Some(variants) => enum_view(&mut out, &data.name, &variants),
            None => {
                struct_view(&mut out, grammar, tokens, &data.name, &data.rule)?;
                structs.push(data.name.clone());
            }
        }
    }
    let _ = write!(
        out,
        "\n/// Whether some view casts a node of `kind`.\n\
         pub fn has_view(kind: SyntaxKind) -> bool {{\n    {}\n}}\n",
        structs
            .iter()
            .map(|s| format!("{s}::can_cast(kind)"))
            .collect::<Vec<_>>()
            .join(" || ")
    );
    Ok(out)
}

/// The variants of a rule that only chooses between nodes.
fn enum_variants(grammar: &Grammar, rule: &Rule) -> Option<Vec<String>> {
    let Rule::Alt(alts) = rule else { return None };
    alts.iter()
        .map(|alt| match alt {
            Rule::Node(node) => Some(grammar[*node].name.clone()),
            _ => None,
        })
        .collect()
}

fn enum_view(out: &mut String, name: &str, variants: &[String]) {
    let _ = write!(
        out,
        "\n#[derive(Clone, Debug, PartialEq, Eq, Hash)]\npub enum {name} {{\n"
    );
    for v in variants {
        let _ = writeln!(out, "    {v}({v}),");
    }
    let _ = write!(
        out,
        "}}\n\nimpl AstNode for {name} {{\n\
         fn can_cast(kind: SyntaxKind) -> bool {{\n\
         {}\n}}\n\n\
         fn cast(syntax: SyntaxNode) -> Option<Self> {{\n\
         match syntax.kind() {{\n{}_ => None,\n}}\n}}\n\n\
         fn syntax(&self) -> &SyntaxNode {{\n\
         match self {{\n{}}}\n}}\n}}\n",
        variants
            .iter()
            .map(|v| format!("{v}::can_cast(kind)"))
            .collect::<Vec<_>>()
            .join(" || "),
        variants
            .iter()
            .map(|v| format!("SyntaxKind::{v} => Some({name}::{v}({v} {{ syntax }})),\n"))
            .collect::<String>(),
        variants
            .iter()
            .map(|v| format!("{name}::{v}(it) => &it.syntax,\n"))
            .collect::<String>(),
    );
    for v in variants {
        let _ = write!(
            out,
            "\nimpl From<{v}> for {name} {{\n\
             fn from(node: {v}) -> {name} {{\n{name}::{v}(node)\n}}\n}}\n"
        );
    }
}

/// One node child of a rule, as written in it.
struct Occurrence {
    ty: String,
    label: Option<String>,
    repeated: bool,
    /// The plain tokens directly before and after it in its sequence.
    before: Option<String>,
    after: Option<String>,
}

fn struct_view(
    out: &mut String,
    grammar: &Grammar,
    tokens: &BTreeMap<String, String>,
    name: &str,
    rule: &Rule,
) -> Result<()> {
    let mut nodes = Vec::new();
    let mut token_fields = Vec::new();
    collect(grammar, rule, false, false, &mut nodes, &mut token_fields)?;
    let _ = write!(
        out,
        "\n#[derive(Clone, Debug, PartialEq, Eq, Hash)]\n\
         pub struct {name} {{\n    pub(super) syntax: SyntaxNode,\n}}\n\n\
         impl AstNode for {name} {{\n\
         fn can_cast(kind: SyntaxKind) -> bool {{\nkind == SyntaxKind::{name}\n}}\n\n\
         fn cast(syntax: SyntaxNode) -> Option<Self> {{\n\
         Self::can_cast(syntax.kind()).then_some({name} {{ syntax }})\n}}\n\n\
         fn syntax(&self) -> &SyntaxNode {{\n&self.syntax\n}}\n}}\n"
    );
    let mut methods = String::new();
    for accessor in node_accessors(name, tokens, &nodes)? {
        let _ = writeln!(methods, "{accessor}");
    }
    let mut seen = Vec::new();
    for token in token_fields {
        if seen.contains(&token) {
            continue;
        }
        let kind = tokens
            .get(&token)
            .with_context(|| format!("{name}: token {token:?} has no kind"))?;
        let method = format!("{}_token", snake(kind.strip_suffix("Kw").unwrap_or(kind)));
        let _ = write!(
            methods,
            "pub fn {method}(&self) -> Option<SyntaxToken> {{\n\
             support::token(&self.syntax, SyntaxKind::{kind})\n}}\n\n"
        );
        seen.push(token);
    }
    if !methods.is_empty() {
        let _ = write!(out, "\nimpl {name} {{\n{}}}\n", methods.trim_end());
        out.push('\n');
    }
    Ok(())
}

/// Gathers a rule's node children and its tokens outside alternatives.
fn collect(
    grammar: &Grammar,
    rule: &Rule,
    repeated: bool,
    in_alt: bool,
    nodes: &mut Vec<Occurrence>,
    tokens: &mut Vec<String>,
) -> Result<()> {
    match rule {
        Rule::Node(node) => nodes.push(occurrence(grammar, *node, None, repeated)),
        Rule::Labeled { label, rule } => {
            let (node, repeated) = match &**rule {
                Rule::Node(node) => (*node, repeated),
                Rule::Rep(rule) => match &**rule {
                    Rule::Node(node) => (*node, true),
                    _ => bail!("label {label} must name a node"),
                },
                _ => bail!("label {label} must name a node"),
            };
            nodes.push(occurrence(grammar, node, Some(label.clone()), repeated));
        }
        Rule::Token(token) => {
            if !in_alt {
                tokens.push(grammar[*token].name.clone());
            }
        }
        Rule::Opt(rule) => collect(grammar, rule, repeated, in_alt, nodes, tokens)?,
        Rule::Rep(rule) => collect(grammar, rule, true, in_alt, nodes, tokens)?,
        Rule::Alt(alts) => {
            for alt in alts {
                collect(grammar, alt, repeated, true, nodes, tokens)?;
            }
        }
        Rule::Seq(items) => {
            let start = nodes.len();
            for item in items {
                collect(grammar, item, repeated, in_alt, nodes, tokens)?;
            }
            // Record the plain tokens around each node written directly in
            // this sequence.
            let plain = |rule: Option<&Rule>| match rule {
                Some(Rule::Token(token)) => Some(grammar[*token].name.clone()),
                _ => None,
            };
            let mut index = start;
            for (i, item) in items.iter().enumerate() {
                if matches!(item, Rule::Node(_) | Rule::Labeled { .. }) {
                    let occurrence = &mut nodes[index];
                    occurrence.before = plain(i.checked_sub(1).map(|j| &items[j]));
                    occurrence.after = plain(items.get(i + 1));
                }
                index = start + count_nodes(&items[..=i]);
            }
        }
    }
    Ok(())
}

fn count_nodes(rules: &[Rule]) -> usize {
    rules
        .iter()
        .map(|rule| match rule {
            Rule::Node(_) | Rule::Labeled { .. } => 1,
            Rule::Token(_) => 0,
            Rule::Opt(rule) | Rule::Rep(rule) => count_nodes(std::slice::from_ref(rule)),
            Rule::Alt(rules) | Rule::Seq(rules) => count_nodes(rules),
        })
        .sum()
}

fn occurrence(grammar: &Grammar, node: Node, label: Option<String>, repeated: bool) -> Occurrence {
    Occurrence {
        ty: grammar[node].name.clone(),
        label,
        repeated,
        before: None,
        after: None,
    }
}

/// One accessor per field, in the order of the rule.
fn node_accessors(
    name: &str,
    tokens: &BTreeMap<String, String>,
    nodes: &[Occurrence],
) -> Result<Vec<String>> {
    let mut by_type: BTreeMap<&str, Vec<&Occurrence>> = BTreeMap::new();
    for o in nodes {
        by_type.entry(&o.ty).or_default().push(o);
    }
    let mut accessors = Vec::new();
    let mut done = Vec::new();
    for o in nodes {
        if done.contains(&o.ty) {
            continue;
        }
        done.push(o.ty.clone());
        let all = &by_type[o.ty.as_str()];
        let labels: Vec<_> = all.iter().map(|o| o.label.clone()).collect();
        let shared = labels.iter().all(|l| *l == labels[0]);
        if shared {
            let base = labels[0].clone().unwrap_or_else(|| snake(&o.ty));
            let ty = &o.ty;
            let accessor = if all.len() == 1 && !o.repeated {
                format!(
                    "pub fn {}(&self) -> Option<{ty}> {{\nsupport::child(&self.syntax)\n}}\n",
                    escape(&base)
                )
            } else {
                let method = if labels[0].is_some() {
                    base
                } else {
                    plural(&base)
                };
                format!(
                    "pub fn {method}(&self) -> AstChildren<{ty}> {{\nsupport::children(&self.syntax)\n}}\n"
                )
            };
            accessors.push(accessor);
            continue;
        }
        // Distinct labels: tell them apart by neighbouring tokens or by
        // position.
        for (index, field) in all.iter().enumerate() {
            let label = field
                .label
                .as_ref()
                .with_context(|| format!("{name}: label every {} or none", field.ty))?;
            let ty = &field.ty;
            let accessor = if field.repeated {
                ensure!(
                    index + 1 == all.len(),
                    "{name}: only the last {ty} may repeat"
                );
                format!(
                    "pub fn {label}(&self) -> impl Iterator<Item = {ty}> + use<> {{\n\
                     support::children(&self.syntax).skip({index})\n}}\n"
                )
            } else if let Some(token) = &field.before {
                format!(
                    "pub fn {label}(&self) -> Option<{ty}> {{\n\
                     support::child_after(&self.syntax, SyntaxKind::{})\n}}\n",
                    tokens[token]
                )
            } else if let Some(token) = &field.after {
                format!(
                    "pub fn {label}(&self) -> Option<{ty}> {{\n\
                     support::child_before(&self.syntax, SyntaxKind::{})\n}}\n",
                    tokens[token]
                )
            } else {
                ensure!(
                    all[..index].iter().all(|o| !o.repeated),
                    "{name}: {label} has no fixed position"
                );
                let nth = match index {
                    0 => "next()".to_string(),
                    _ => format!("nth({index})"),
                };
                format!(
                    "pub fn {label}(&self) -> Option<{ty}> {{\n\
                     support::children::<{ty}>(&self.syntax).{nth}\n}}\n"
                )
            };
            accessors.push(accessor);
        }
    }
    Ok(accessors)
}

fn snake(camel: &str) -> String {
    let mut out = String::new();
    for (i, c) in camel.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn plural(name: &str) -> String {
    if name.ends_with('s') || name.ends_with('h') || name.ends_with('x') {
        format!("{name}es")
    } else {
        format!("{name}s")
    }
}

/// A method name that is not a Rust keyword.
fn escape(name: &str) -> String {
    match name {
        "type" => "ty".to_string(),
        _ => name.to_string(),
    }
}

/// Formats with the workspace's rustfmt settings, as `cargo fmt` would.
fn format(root: &Path, code: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .current_dir(root)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .context("running rustfmt")?;
    child
        .stdin
        .take()
        .expect("piped stdin")
        .write_all(code.as_bytes())?;
    let output = child.wait_with_output()?;
    ensure!(
        output.status.success(),
        "rustfmt rejected the generated code"
    );
    Ok(String::from_utf8(output.stdout)?)
}
