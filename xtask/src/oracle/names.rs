//! `cargo xtask oracle names`: what each pinned elm reports on projects
//! that get names wrong, for the naming-error ratchets (plan 5.4). The
//! curated cases under `crates/engine/tests/names/cases` each aim at one
//! of `Reporting/Error/Canonicalize.hs`'s errors; the mutations edit the
//! seeds under `seeds/` the ways people get names wrong, and
//! `mutations.tsv` lists them, so the tests make the same projects. Every
//! project builds with the fixture packages (plan 5.3).

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use nomi_syntax::ast::{self, AstNode};
use nomi_syntax::{SyntaxKind, SyntaxNode, SyntaxToken, parse_module};
use nomi_testkit::edit::{self, Edit};
use nomi_testkit::transcript::Case;

use super::modules::{case_files, pinned, read_case, record_projects};
use crate::references::References;

pub const DIR: &str = "crates/engine/tests/names";

pub const HEADER: &str = "# @generated by `cargo xtask oracle names`; regenerate, never edit.";

/// The packages every project may use: the fixture packages.
const PACKAGES: [&str; 10] = [
    "elm/core",
    "elm/json",
    "elm/html",
    "elm/browser",
    "elm/url",
    "elm/virtual-dom",
    "elm/time",
    "elm/http",
    "elm/bytes",
    "elm/file",
];

pub fn run(root: &Path, refs: &References) -> Result<()> {
    let dir = root.join(DIR);
    let mut projects = Vec::new();
    for (stem, path) in case_files(&dir.join("cases"))? {
        projects.push((format!("case/{stem}"), read_case(&path)?));
    }
    let mut table = format!("{HEADER}\n{}\n", edit::HEADER);
    for (seed, path) in case_files(&dir.join("seeds"))? {
        let case = read_case(&path)?;
        projects.push((format!("seed/{seed}"), case.clone()));
        for edit in mutations(&seed, &case) {
            table.push_str(&edit.to_line());
            table.push('\n');
            projects.push((format!("mutation/{}", edit.id), edit.apply(&case)));
        }
    }
    fs::write(dir.join("mutations.tsv"), table)?;
    let pinned = pinned(root, &PACKAGES)?;
    record_projects(refs, &dir, "names", &pinned, &projects).context("recording")
}

/// The ways `case`'s modules get names wrong, in a stable order.
pub fn mutations(seed: &str, case: &Case) -> Vec<Edit> {
    let mut edits = Vec::new();
    for (file, text) in &case.files {
        if !file.ends_with(".elm") {
            continue;
        }
        let parse = parse_module(text);
        let root = parse.syntax();
        let mut add = |kind: &str, start: usize, end: usize, text: String, note: String| {
            let n = edits
                .iter()
                .filter(|e: &&Edit| e.id.starts_with(&format!("{seed}/{kind}/")))
                .count();
            edits.push(Edit {
                id: format!("{seed}/{kind}/{n}"),
                seed: seed.to_owned(),
                file: file.clone(),
                start,
                end,
                text,
                note,
            });
        };
        for node in root.descendants() {
            match node.kind() {
                // A misspelled reference to a value, type or constructor.
                SyntaxKind::NameExpr | SyntaxKind::NamedType | SyntaxKind::ConstructorPattern => {
                    if let Some(name) = last_ident(&node) {
                        let (start, end) = range(&name);
                        add(
                            "rename",
                            start,
                            end,
                            typo(name.text()),
                            format!("{} misspelled", name.text()),
                        );
                    }
                }
                // A name taken out of an import's exposing list, or a
                // misspelled one in the module's own.
                SyntaxKind::ExposingList => {
                    let items: Vec<SyntaxNode> = node
                        .children()
                        .filter(|c| ast::Exposed::can_cast(c.kind()))
                        .collect();
                    let in_import = node
                        .parent()
                        .is_some_and(|p| p.kind() == SyntaxKind::Import);
                    for (i, item) in items.iter().enumerate() {
                        let (start, end) = trimmed(item);
                        if in_import {
                            if items.len() < 2 {
                                continue;
                            }
                            // With the comma after it, or the last one's before it.
                            let (start, end) = match items.get(i + 1) {
                                Some(next) => (start, trimmed(next).0),
                                None => (trimmed(&items[i - 1]).1, end),
                            };
                            add(
                                "unexpose",
                                start,
                                end,
                                String::new(),
                                format!("{} not imported", item.text()),
                            );
                        } else if let Some(name) = item.first_token() {
                            let (start, end) = range(&name);
                            add(
                                "export",
                                start,
                                end,
                                typo(name.text()),
                                format!("exposing {} misspelled", name.text()),
                            );
                        }
                    }
                }
                // An import left out.
                SyntaxKind::Import => {
                    let (start, end) = trimmed(&node);
                    let end = (end + 1).min(text.len());
                    add(
                        "unimport",
                        start,
                        end,
                        String::new(),
                        format!("{} left out", node.text().to_string().trim()),
                    );
                }
                // A declaration written twice.
                SyntaxKind::ValueDecl | SyntaxKind::TypeAliasDecl | SyntaxKind::CustomTypeDecl
                    if node
                        .parent()
                        .is_some_and(|p| p.kind() == SyntaxKind::Module) =>
                {
                    let (start, end) = trimmed(&node);
                    let copy = format!("\n\n\n{}", &text[start..end]);
                    add(
                        "duplicate",
                        end,
                        end,
                        copy,
                        "a declaration written twice".to_owned(),
                    );
                }
                SyntaxKind::Definition => definition(&node, &mut add),
                _ => {}
            }
            // A type given one argument fewer.
            if node.kind() == SyntaxKind::NamedType {
                let args: Vec<SyntaxNode> = node
                    .children()
                    .filter(|c| ast::Type::can_cast(c.kind()))
                    .collect();
                if let Some(last) = args.last() {
                    let start = match args.len() {
                        1 => node.first_token().map_or(0, |t| range(&t).1),
                        n => trimmed(&args[n - 2]).1,
                    };
                    let end = trimmed(last).1;
                    add(
                        "arity",
                        start,
                        end,
                        String::new(),
                        "a type argument left out".to_owned(),
                    );
                }
            }
        }
    }
    edits
}

/// The mutations of one definition: a parameter named as another, a
/// local named as a parameter, and a value defined as itself.
fn definition(node: &SyntaxNode, add: &mut impl FnMut(&str, usize, usize, String, String)) {
    let params: Vec<SyntaxToken> = node
        .children()
        .filter(|c| c.kind() == SyntaxKind::VarPattern)
        .filter_map(|c| c.first_token())
        .collect();
    if let [first, second, ..] = &params[..] {
        let (start, end) = range(second);
        add(
            "duplicate-param",
            start,
            end,
            first.text().to_owned(),
            format!("{} named {}", second.text(), first.text()),
        );
    }
    if let Some(first) = params.first() {
        // Locals bound inside the body, renamed to the first parameter.
        let body = node.children().find(|c| ast::Expr::can_cast(c.kind()));
        for local in body.iter().flat_map(|b| b.descendants()) {
            if local.kind() == SyntaxKind::VarPattern
                && let Some(name) = local.first_token()
                && name.text() != first.text()
            {
                let (start, end) = range(&name);
                add(
                    "shadow",
                    start,
                    end,
                    first.text().to_owned(),
                    format!("{} named {}", name.text(), first.text()),
                );
            }
        }
    }
    let name = node
        .children_with_tokens()
        .filter_map(|e| e.into_token())
        .find(|t| t.kind() == SyntaxKind::LowerIdent);
    let body = node
        .children()
        .filter(|c| ast::Expr::can_cast(c.kind()))
        .last();
    if params.is_empty()
        && node.children().all(|c| !ast::Pattern::can_cast(c.kind()))
        && let (Some(name), Some(body)) = (name, body)
        && body.kind() != SyntaxKind::LambdaExpr
    {
        let (start, end) = trimmed(&body);
        add(
            "cycle",
            start,
            end,
            name.text().to_owned(),
            format!("{} defined as itself", name.text()),
        );
    }
}

fn last_ident(node: &SyntaxNode) -> Option<SyntaxToken> {
    node.children_with_tokens()
        .filter_map(|e| e.into_token())
        .filter(|t| matches!(t.kind(), SyntaxKind::LowerIdent | SyntaxKind::UpperIdent))
        .last()
}

fn range(token: &SyntaxToken) -> (usize, usize) {
    let range = token.text_range();
    (range.start().into(), range.end().into())
}

/// From `node`'s first token that isn't trivia to its last.
fn trimmed(node: &SyntaxNode) -> (usize, usize) {
    let mut tokens = node
        .descendants_with_tokens()
        .filter_map(|e| e.into_token())
        .filter(|t| !t.kind().is_trivia());
    let first = tokens
        .next()
        .map_or(node.text_range().start(), |t| t.text_range().start());
    let last = tokens
        .last()
        .map_or(node.text_range().end(), |t| t.text_range().end());
    (first.into(), last.into())
}

/// `name` with its last two letters swapped, or doubled when it has one.
fn typo(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    match chars.len() {
        0 | 1 => format!("{name}{name}"),
        n if chars[n - 1] == chars[n - 2] => format!("{name}x"),
        n => {
            let mut swapped = chars.clone();
            swapped.swap(n - 1, n - 2);
            swapped.into_iter().collect()
        }
    }
}
