//! `cargo xtask oracle syntax`: whether each pinned elm release and
//! elm-format accept each mutation of the syntax suite's seeds and each
//! corpus module, stored for the syntax ratchets.
//!
//! elm runs in the [`sandbox`](super::sandbox)es, one module at a time:
//! batching several modules in one `elm make` breaks as soon as two parse
//! with the same name (`Build.hs`, `checkUniqueRoots`).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::sync::Mutex;
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

use anyhow::{Context, Result, ensure};
use nomi_syntax::Source;
use nomi_testkit::mutation;

use super::sandbox::{self, Outcome, Sandbox};
use super::{binary_path, cache_dir};
use crate::corpus::compat::{self, Version};
use crate::corpus::syntax as corpus_syntax;
use crate::references::References;

/// The mutation suite: seeds, stored verdicts and `passing.txt`.
pub const MUTATIONS: &str = "crates/syntax/tests/syntax_mutations";

pub const HEADER: &str = "# @generated by `cargo xtask oracle syntax`; regenerate, never edit.";

/// Which inputs to run.
#[derive(Clone, Copy, Debug, PartialEq, Eq, clap::ValueEnum)]
pub enum Inputs {
    Mutations,
    Corpus,
}

/// One module to check, and the kind of project it belongs to.
#[derive(Debug)]
pub struct Job {
    /// What the job checks, for messages.
    pub name: String,
    pub source: Source,
    pub text: Vec<u8>,
}

/// A seed of the mutation suite, as `seeds.txt` lists it.
#[derive(Debug)]
pub struct Seed {
    pub name: String,
    pub source: Source,
    pub text: String,
}

pub fn run(root: &Path, refs: &References, inputs: Option<Inputs>, jobs: usize) -> Result<()> {
    let tools = Tools::new(root, refs)?;
    if inputs != Some(Inputs::Corpus) {
        mutations(root, &tools, jobs)?;
    }
    if inputs != Some(Inputs::Mutations) {
        corpus(root, &tools, jobs)?;
    }
    Ok(())
}

pub fn seeds(root: &Path) -> Result<Vec<Seed>> {
    let dir = root.join(MUTATIONS);
    let list = std::fs::read_to_string(dir.join("seeds.txt")).context("reading seeds.txt")?;
    let mut seeds = Vec::new();
    for line in list
        .lines()
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
    {
        let words: Vec<&str> = line.split_whitespace().collect();
        let [name, source, file] = words[..] else {
            anyhow::bail!("seeds.txt: malformed line `{line}`");
        };
        let source = match source {
            "application" => Source::Application,
            "package" => Source::Package,
            "kernel" => Source::Kernel,
            _ => anyhow::bail!("seeds.txt: unknown kind `{source}`"),
        };
        let path = dir.join("seeds").join(file);
        let text = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        seeds.push(Seed {
            name: name.to_owned(),
            source,
            text,
        });
    }
    Ok(seeds)
}

fn mutations(root: &Path, tools: &Tools, jobs: usize) -> Result<()> {
    let out = root.join(MUTATIONS).join("oracle");
    std::fs::create_dir_all(&out)?;
    for seed in seeds(root)? {
        let mutations = mutation::suite(&seed.name, &seed.text);
        eprintln!("==> {} ({} mutations)", seed.name, mutations.len());
        let work: Vec<Job> = mutations
            .iter()
            .map(|m| Job {
                name: format!("{} / {}", seed.name, m.name),
                source: seed.source,
                text: m.source.clone().into_bytes(),
            })
            .collect();
        let outcomes = tools.run(&work, jobs)?;
        let mut table = format!(
            "{HEADER}\n# sources {}\n{}",
            mutation::digest(&mutations),
            tools.columns("case")
        );
        for (m, row) in mutations.iter().zip(&outcomes) {
            writeln!(table, "{}\t{}", m.name, render_row(row)).unwrap();
        }
        std::fs::write(out.join(format!("{}.tsv", seed.name)), table)?;
    }
    Ok(())
}

fn corpus(root: &Path, tools: &Tools, jobs: usize) -> Result<()> {
    let modules = corpus_syntax::modules(root)?;
    eprintln!("==> corpus ({} modules)", modules.len());
    let work: Vec<Job> = modules
        .iter()
        .map(|m| {
            Ok(Job {
                name: format!("{} {}", m.case, m.path),
                source: m.source,
                text: std::fs::read(&m.file)?,
            })
        })
        .collect::<Result<_>>()?;
    let outcomes = tools.run(&work, jobs)?;
    let mut table = format!(
        "{HEADER}\n# modules {} sources {}\n{}",
        modules.len(),
        corpus_syntax::digest(&modules)?,
        tools.columns("case\tpath")
    );
    // Only modules some tool rejects; the rest are accepted everywhere.
    for (m, row) in modules.iter().zip(&outcomes) {
        if row.iter().any(|o| *o != Outcome::Accepted) {
            writeln!(table, "{}\t{}\t{}", m.case, m.path, render_row(row)).unwrap();
        }
    }
    let path = root.join(corpus_syntax::DIR).join("oracle.tsv");
    std::fs::create_dir_all(path.parent().unwrap())?;
    std::fs::write(path, table)?;
    Ok(())
}

fn render_row(row: &[Outcome]) -> String {
    let cells: Vec<&str> = row
        .iter()
        .map(|o| match o {
            Outcome::Accepted => "ok",
            Outcome::Rejected(detail) => detail,
            Outcome::Crashed => corpus_syntax::CRASH,
        })
        .collect();
    cells.join("\t")
}

/// Every pinned elm, oldest first, then elm-format.
struct Tools {
    root: PathBuf,
    elms: Vec<(Version, PathBuf)>,
    elm_format: PathBuf,
}

impl Tools {
    fn new(root: &Path, refs: &References) -> Result<Tools> {
        let binary = |name: &str, version: &str| -> Result<PathBuf> {
            let binary = refs
                .binary
                .iter()
                .find(|b| b.name == name && b.version == version)
                .with_context(|| format!("{name} {version} is not pinned"))?;
            let path = binary_path(binary)?;
            ensure!(
                path.exists(),
                "{} is missing; run `cargo xtask oracle fetch`",
                path.display()
            );
            Ok(path)
        };
        let elms = compat::compats(refs)?
            .into_iter()
            .map(|v| Ok((v, binary("elm", &v.to_string())?)))
            .collect::<Result<_>>()?;
        let format = refs
            .binary
            .iter()
            .find(|b| b.name == "elm-format")
            .context("elm-format is not pinned")?;
        Ok(Tools {
            root: root.to_path_buf(),
            elms,
            elm_format: binary("elm-format", &format.version)?,
        })
    }

    fn columns(&self, first: &str) -> String {
        let mut line = first.to_owned();
        for (version, _) in &self.elms {
            write!(line, "\telm {version}").unwrap();
        }
        line.push_str("\telm-format\n");
        line
    }

    /// Every tool's outcome for every job, in order, on `workers` threads
    /// with sandboxes of their own.
    fn run(&self, work: &[Job], workers: usize) -> Result<Vec<Vec<Outcome>>> {
        let queue = Queue {
            work,
            next: AtomicUsize::new(0),
            done: AtomicUsize::new(0),
            failed: AtomicBool::new(false),
            results: Mutex::new((0..work.len()).map(|_| None).collect()),
        };
        let dir = cache_dir()?.join("sandboxes").join("syntax");
        std::thread::scope(|scope| {
            let handles: Vec<_> = (0..workers.min(work.len()))
                .map(|w| {
                    let (queue, dir) = (&queue, dir.join(w.to_string()));
                    scope.spawn(move || {
                        let result = self.work(&dir, queue);
                        if result.is_err() {
                            queue.failed.store(true, Ordering::Relaxed);
                        }
                        result
                    })
                })
                .collect();
            handles
                .into_iter()
                .try_for_each(|h| h.join().expect("a worker panicked"))
        })?;
        Ok(queue
            .results
            .into_inner()
            .unwrap()
            .into_iter()
            .map(|r| r.expect("every job ran"))
            .collect())
    }

    /// One worker: its sandboxes, then jobs until none are left or another
    /// worker failed.
    fn work(&self, dir: &Path, queue: &Queue) -> Result<()> {
        let sandboxes = self
            .elms
            .iter()
            .map(|(v, elm)| Sandbox::create(&dir.join(v.to_string()), elm, *v, &self.root))
            .collect::<Result<Vec<_>>>()?;
        while !queue.failed.load(Ordering::Relaxed) {
            let i = queue.next.fetch_add(1, Ordering::Relaxed);
            let Some(job) = queue.work.get(i) else { break };
            let mut row = Vec::with_capacity(sandboxes.len() + 1);
            for sandbox in &sandboxes {
                row.push(
                    sandbox
                        .check(job.source, &job.text)
                        .with_context(|| job.name.clone())?,
                );
            }
            row.push(
                sandbox::elm_format(&self.elm_format, &job.text)
                    .with_context(|| job.name.clone())?,
            );
            queue.results.lock().unwrap()[i] = Some(row);
            let n = queue.done.fetch_add(1, Ordering::Relaxed) + 1;
            if n.is_multiple_of(1000) {
                eprintln!("  {n}/{}", queue.work.len());
            }
        }
        Ok(())
    }
}

struct Queue<'a> {
    work: &'a [Job],
    next: AtomicUsize,
    done: AtomicUsize,
    failed: AtomicBool,
    results: Mutex<Vec<Option<Vec<Outcome>>>>,
}
