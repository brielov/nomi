//! `cargo xtask oracle javascript`: the JavaScript each pinned elm
//! generates for each fixture program in each mode, for the engine's
//! `javascript` ratchet.
//!
//! A case is a project as the modules oracle has them, `elm make`'s
//! arguments and files, with `default.elm.json` for an `elm.json` it
//! doesn't have and an application's `elm-version` rewritten to the
//! elm's. Its output is `out.js` unless its arguments name one, as an
//! HTML case does. Each elm builds every case offline with its own `ELM_HOME`
//! once in each mode: dev, `--debug` and `--optimize`. The outputs are
//! large, so `expected.sha256` keeps their hashes, as the ratchet reads
//! them, and the files stay in the sandbox for a look; a mode elm refuses
//! is left out, with why, in `refused.tsv`.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process::Command;

use anyhow::{Context, Result, ensure};
use nomi_testkit::transcript::Case;

use super::modules::{case_files, pinned, read_case, with_elm_version};
use super::sandbox::{elm_home, offline};
use super::{binary_path, cache_dir};
use crate::corpus::compat::{self, Version};
use crate::download::sha256;
use crate::references::References;

pub(crate) const CASES: &str = "crates/engine/tests/javascript";

/// The packages the cases may depend on.
const DEPENDENCIES: [&str; 7] = [
    "elm/browser",
    "elm/core",
    "elm/html",
    "elm/json",
    "elm/time",
    "elm/url",
    "elm/virtual-dom",
];

/// Each mode, by the name a case's id gives it, and its flag.
pub(crate) const MODES: [(&str, Option<&str>); 3] = [
    ("dev", None),
    ("debug", Some("--debug")),
    ("optimize", Some("--optimize")),
];

pub(crate) fn run(root: &Path, refs: &References) -> Result<()> {
    let dir = root.join(CASES);
    let pinned = pinned(root, &DEPENDENCIES)?;
    let default = fs::read_to_string(dir.join("default.elm.json"))?;
    let mut cases = Vec::new();
    for (stem, path) in case_files(&dir.join("cases"))? {
        cases.push((stem, read_case(&path)?));
    }
    let mut hashes = String::new();
    let mut refused =
        String::from("# @generated by `cargo xtask oracle javascript`; regenerate, never edit.\n");
    for version in compat::compats(refs)? {
        let scratch = cache_dir()?
            .join("sandboxes")
            .join("javascript")
            .join(version.to_string());
        if scratch.exists() {
            fs::remove_dir_all(&scratch)?;
        }
        let home = scratch.join("home");
        elm_home(&home, version, &pinned)?;
        let out = scratch.join("out");
        fs::create_dir_all(&out)?;
        for (id, case) in &cases {
            for (mode, flag) in MODES {
                let run = format!("{id} {mode} as {version}");
                match build(refs, &scratch, &home, version, case, &default, flag)
                    .with_context(|| format!("elm on {run}"))?
                {
                    Ok(js) => {
                        writeln!(hashes, "{}  {run}", sha256(&js))?;
                        let extension = if output(case).ends_with(".html") {
                            "html"
                        } else {
                            "js"
                        };
                        fs::write(out.join(format!("{id}.{mode}.{extension}")), &js)?;
                    }
                    Err(title) => writeln!(refused, "{run}\t{title}")?,
                }
            }
        }
        eprintln!("  elm {version}: {} cases", cases.len());
    }
    fs::write(dir.join("expected.sha256"), hashes)?;
    fs::write(dir.join("refused.tsv"), refused)?;
    println!("recorded {} cases", cases.len());
    Ok(())
}

/// The JavaScript elm `version` generates for `case` with `flag`, or the
/// title of the report refusing it.
fn build(
    refs: &References,
    scratch: &Path,
    home: &Path,
    version: Version,
    case: &Case,
    default: &str,
    flag: Option<&str>,
) -> Result<Result<Vec<u8>, String>> {
    let pin = (refs.binary.iter())
        .find(|b| b.name == "elm" && b.version == version.to_string())
        .with_context(|| format!("elm {version} is not pinned"))?;
    let elm = binary_path(pin)?;
    ensure!(
        elm.exists(),
        "{} is missing; run `cargo xtask oracle fetch`",
        elm.display()
    );
    let work = scratch.join("work");
    if work.exists() {
        fs::remove_dir_all(&work)?;
    }
    fs::create_dir_all(&work)?;
    case.create_files(&work)?;
    let manifest = work.join("elm.json");
    let text = fs::read_to_string(&manifest).unwrap_or_else(|_| default.to_owned());
    fs::write(&manifest, with_elm_version(&text, version))?;
    let file = output(case);
    let mut command = Command::new(&elm);
    command
        .args(&case.args)
        .args((!case.args.iter().any(|a| a.starts_with("--output="))).then_some("--output=out.js"))
        .arg("--report=json")
        .args(flag)
        .args(["+RTS", "-N1", "-RTS"])
        .current_dir(&work)
        .env("ELM_HOME", home);
    offline(&mut command);
    let output = command.output().context("running elm")?;
    if output.status.success() {
        return Ok(Ok(fs::read(work.join(file))?));
    }
    let report: serde_json::Value = serde_json::from_slice(&output.stderr).unwrap_or_default();
    let title = (report["title"].as_str())
        .or_else(|| report["errors"][0]["problems"][0]["title"].as_str())
        .unwrap_or("?");
    Ok(Err(title.to_owned()))
}

/// The file `case` makes: the one its arguments name, or `out.js`.
fn output(case: &Case) -> &str {
    (case.args.iter())
        .find_map(|a| a.strip_prefix("--output="))
        .unwrap_or("out.js")
}
