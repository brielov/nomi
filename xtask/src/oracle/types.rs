//! `cargo xtask oracle types`: what each pinned elm reports on projects
//! with type errors, for the type-error ratchets (plan 6.9). The curated
//! cases under `crates/engine/tests/types/cases` each aim at one of
//! `Reporting/Error/Type.hs`'s reports; the mutations edit the seeds
//! under `seeds/` the ways people get types wrong (a literal of another
//! type, two arguments swapped, an annotation edited), and
//! `mutations.tsv` lists them, so the tests make the same projects.
//! Every project builds with the fixture packages.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use nomi_syntax::{SyntaxKind, SyntaxNode, parse_module};
use nomi_testkit::edit::{self, Edit};
use nomi_testkit::transcript::Case;

use super::modules::{case_files, pinned, read_case, record_projects};
use crate::references::References;

pub const DIR: &str = "crates/engine/tests/types";

pub const HEADER: &str = "# @generated by `cargo xtask oracle types`; regenerate, never edit.";

/// The packages every project may use, as the naming projects use.
const PACKAGES: [&str; 10] = [
    "elm/core",
    "elm/json",
    "elm/html",
    "elm/browser",
    "elm/url",
    "elm/virtual-dom",
    "elm/time",
    "elm/http",
    "elm/bytes",
    "elm/file",
];

pub fn run(root: &Path, refs: &References) -> Result<()> {
    let dir = root.join(DIR);
    let mut projects = Vec::new();
    for (stem, path) in case_files(&dir.join("cases"))? {
        projects.push((format!("case/{stem}"), read_case(&path)?));
    }
    let mut table = format!("{HEADER}\n{}\n", edit::HEADER);
    for (seed, path) in case_files(&dir.join("seeds"))? {
        let case = read_case(&path)?;
        projects.push((format!("seed/{seed}"), case.clone()));
        for edit in mutations(&seed, &case) {
            table.push_str(&edit.to_line());
            table.push('\n');
            projects.push((format!("mutation/{}", edit.id), edit.apply(&case)));
        }
    }
    fs::write(dir.join("mutations.tsv"), table)?;
    let pinned = pinned(root, &PACKAGES)?;
    record_projects(refs, &dir, "types", &pinned, &projects).context("recording")
}

/// The ways `case`'s modules get types wrong, in a stable order.
pub fn mutations(seed: &str, case: &Case) -> Vec<Edit> {
    let mut edits = Vec::new();
    for (file, text) in &case.files {
        if !file.ends_with(".elm") {
            continue;
        }
        let root = parse_module(text).syntax();
        let mut add = |kind: &str, start: usize, end: usize, text: String, note: String| {
            let prefix = format!("{seed}/{kind}/");
            let n = edits
                .iter()
                .filter(|e: &&Edit| e.id.starts_with(&prefix))
                .count();
            edits.push(Edit {
                id: format!("{prefix}{n}"),
                seed: seed.to_owned(),
                file: file.clone(),
                start,
                end,
                text,
                note,
            });
        };
        for node in root.descendants() {
            match node.kind() {
                // A literal of another type.
                SyntaxKind::LiteralExpr => {
                    let Some(token) = node.first_token() else {
                        continue;
                    };
                    let other = match token.kind() {
                        SyntaxKind::Int | SyntaxKind::Float => "\"x\"",
                        SyntaxKind::String | SyntaxKind::MultilineString => "0",
                        SyntaxKind::Char => "\"c\"",
                        _ => continue,
                    };
                    let range = token.text_range();
                    add(
                        "literal",
                        range.start().into(),
                        range.end().into(),
                        other.to_owned(),
                        format!("{} written as {other}", token.text()),
                    );
                }
                // The first two arguments of a call swapped.
                SyntaxKind::CallExpr => {
                    let parts: Vec<SyntaxNode> = node.children().collect();
                    if let [_, first, second, ..] = &parts[..] {
                        let (a, b) = (trimmed(first), trimmed(second));
                        let swapped =
                            format!("{}{}{}", &text[b.0..b.1], &text[a.1..b.0], &text[a.0..a.1]);
                        add(
                            "swap",
                            a.0,
                            b.1,
                            swapped,
                            "two arguments swapped".to_owned(),
                        );
                    }
                }
                // A type in an annotation changed.
                SyntaxKind::NamedType
                    if node.ancestors().any(|a| a.kind() == SyntaxKind::Signature) =>
                {
                    let Some(name) = node
                        .children_with_tokens()
                        .filter_map(|e| e.into_token())
                        .filter(|t| t.kind() == SyntaxKind::UpperIdent)
                        .last()
                    else {
                        continue;
                    };
                    let other = match name.text() {
                        "Int" => "String",
                        "String" => "Int",
                        "Float" => "Int",
                        _ => "Int",
                    };
                    let range = name.text_range();
                    add(
                        "annotation",
                        range.start().into(),
                        range.end().into(),
                        other.to_owned(),
                        format!("{} annotated as {other}", name.text()),
                    );
                }
                _ => {}
            }
        }
    }
    edits
}

/// From `node`'s first token that isn't trivia to its last.
fn trimmed(node: &SyntaxNode) -> (usize, usize) {
    let mut tokens = (node.descendants_with_tokens())
        .filter_map(|e| e.into_token())
        .filter(|t| !t.kind().is_trivia());
    let first = tokens
        .next()
        .map_or(node.text_range().start(), |t| t.text_range().start());
    let last = tokens
        .last()
        .map_or(node.text_range().end(), |t| t.text_range().end());
    (first.into(), last.into())
}
