//! `cargo xtask oracle modules`: what each pinned elm reports for each
//! module-graph case, stored for the engine's report tests.
//!
//! A case is a project: `elm make`'s arguments and its files, with
//! `default.elm.json` standing in for an `elm.json` it doesn't have. Each
//! elm runs offline on a fresh copy with an `ELM_HOME` holding the
//! corpus's elm/core and elm/json, and an application's `elm-version`
//! rewritten to that elm's. The project's directory is padded to 96
//! bytes and written `$ROOT` in elm's `--report=json`, which is otherwise
//! kept as written, in `reports.tsv`; a report several elms write alike is
//! one row naming them all. What elm prints on standard error without
//! `--report`, its terminal report, goes in `terminal.tsv` the same way,
//! as a JSON string. The case's files are dated a second apart in their
//! order, since the terminal report lists modules oldest first. Each
//! package's `elm.json` is stored under `packages/`, so the tests can give
//! nomi the same packages.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, ensure};
use nomi_testkit::transcript::Case;

use super::sandbox::{elm_home, offline};
use super::{binary_path, cache_dir};
use crate::corpus::compat::{self, Version};
use crate::corpus::{corpus_dir, packages};
use crate::references::References;

pub const CASES: &str = "crates/engine/tests/modules";

pub const HEADER: &str = "# @generated by `cargo xtask oracle modules`; regenerate, never edit.";

/// The packages every case's project may depend on.
const DEPENDENCIES: [&str; 2] = ["elm/core", "elm/json"];

/// The length of the project directory's path, written `$ROOT`.
const ROOT_LENGTH: usize = 96;

/// Runs of one case before a lock failure is an error.
const RETRIES: u32 = 5;

pub fn run(root: &Path, refs: &References) -> Result<()> {
    let dir = root.join(CASES);
    let pinned: Vec<packages::Package> = packages::load(root)?
        .packages
        .into_iter()
        .filter(|p| DEPENDENCIES.contains(&p.name.as_str()))
        .collect();
    ensure!(
        pinned.len() == DEPENDENCIES.len(),
        "the corpus doesn't pin {DEPENDENCIES:?}"
    );
    store_packages(&dir.join("packages"), &pinned)?;
    let default = fs::read_to_string(dir.join("default.elm.json"))?;
    let mut names: Vec<String> = fs::read_dir(dir.join("cases"))?
        .map(|entry| Ok(entry?.file_name().to_string_lossy().into_owned()))
        .collect::<Result<_>>()?;
    names.sort();
    let scratch = cache_dir()?.join("sandboxes").join("modules");
    let mut out = format!("{HEADER}\ncase\telms\treport\n");
    let mut terminal = format!("{HEADER}\ncase\telms\tstderr\n");
    for name in &names {
        let stem = name
            .strip_suffix(".case")
            .with_context(|| format!("{name} is not a .case"))?;
        let case = Case::parse(&fs::read_to_string(dir.join("cases").join(name))?)
            .map_err(anyhow::Error::msg)
            .with_context(|| name.clone())?;
        let mut reports: Vec<(Vec<String>, String)> = Vec::new();
        let mut stderrs: Vec<(Vec<String>, String)> = Vec::new();
        for version in compat::compats(refs)? {
            let elm = format!("elm {version}");
            for (json, table) in [(true, &mut reports), (false, &mut stderrs)] {
                let output = record(refs, &scratch, version, &pinned, &case, &default, json)
                    .with_context(|| format!("{elm} on {name}"))?;
                match table.iter_mut().find(|(_, o)| *o == output) {
                    Some((versions, _)) => versions.push(elm.clone()),
                    None => table.push((vec![elm.clone()], output)),
                }
            }
        }
        for (versions, report) in reports {
            writeln!(out, "{stem}\t{}\t{report}", versions.join(","))?;
        }
        for (versions, stderr) in stderrs {
            let stderr = serde_json::to_string(&stderr)?;
            writeln!(terminal, "{stem}\t{}\t{stderr}", versions.join(","))?;
        }
    }
    fs::write(dir.join("reports.tsv"), out)?;
    fs::write(dir.join("terminal.tsv"), terminal)?;
    println!("recorded {} cases", names.len());
    Ok(())
}

/// elm's report on `case`: with `json`, its `--report=json` on one line,
/// or `accepted`; without, what it prints on standard error.
fn record(
    refs: &References,
    scratch: &Path,
    version: Version,
    pinned: &[packages::Package],
    case: &Case,
    default: &str,
    json: bool,
) -> Result<String> {
    let pin = refs
        .binary
        .iter()
        .find(|b| b.name == "elm" && b.version == version.to_string())
        .with_context(|| format!("elm {version} is not pinned"))?;
    let elm = binary_path(pin)?;
    ensure!(
        elm.exists(),
        "{} is missing; run `cargo xtask oracle fetch`",
        elm.display()
    );
    let home = scratch.join("home");
    if scratch.exists() {
        fs::remove_dir_all(scratch)?;
    }
    fs::create_dir_all(scratch)?;
    let work = padded(scratch)?;
    elm_home(&home, version, pinned)?;
    case.create_files(&work)?;
    date_files(&work, case)?;
    let manifest = work.join("elm.json");
    let text = match fs::read_to_string(&manifest) {
        Ok(text) => text,
        Err(_) => default.to_owned(),
    };
    fs::write(&manifest, with_elm_version(&text, version))?;
    let mut attempt = 1;
    let output = loop {
        let mut command = Command::new(&elm);
        command
            .args(&case.args)
            .arg("--output=/dev/null")
            .args(json.then_some("--report=json"))
            .args(["+RTS", "-N1", "-RTS"])
            .current_dir(&work)
            .env("ELM_HOME", &home);
        offline(&mut command);
        let output = command.output().context("running elm")?;
        // elm now and then trips over its own lock on `d.dat`.
        let locked = String::from_utf8_lossy(&output.stderr).contains("(file is locked)");
        if !locked || attempt == RETRIES {
            break output;
        }
        attempt += 1;
    };
    let work = canonical(&work)?;
    if !json {
        let stderr = String::from_utf8(output.stderr)?;
        return Ok(stderr.replace(&work, "$ROOT"));
    }
    let json = [&output.stderr, &output.stdout]
        .into_iter()
        .find(|o| o.starts_with(b"{"));
    let Some(json) = json else {
        ensure!(
            output.status.success(),
            "elm exited with {} and no report:\n{}",
            output.status,
            String::from_utf8_lossy(&output.stderr)
        );
        return Ok("accepted".to_owned());
    };
    // One line: elm escapes the newlines it writes.
    let report = String::from_utf8(json.trim_ascii_end().to_vec())?;
    Ok(report.replace(&work, "$ROOT"))
}

/// Dates the case's files a second apart in their order, from 2001, so
/// the terminal report's order, oldest first, is the same on every run.
pub fn date_files(dir: &Path, case: &Case) -> Result<()> {
    let start = std::time::UNIX_EPOCH + std::time::Duration::from_secs(978_307_200);
    for (i, (path, _)) in case.files.iter().enumerate() {
        let file = fs::File::options().write(true).open(dir.join(path))?;
        file.set_modified(start + std::time::Duration::from_secs(i as u64))?;
    }
    Ok(())
}

/// An application's `elm.json` with `elm-version` set to `version`; a
/// package's as it is.
pub fn with_elm_version(text: &str, version: Version) -> String {
    if !text.contains("\"type\": \"application\"") {
        return text.to_owned();
    }
    const KEY: &str = "\"elm-version\": \"";
    let Some(start) = text.find(KEY).map(|at| at + KEY.len()) else {
        return text.to_owned();
    };
    let end = start + text[start..].find('"').unwrap_or(0);
    format!("{}{version}{}", &text[..start], &text[end..])
}

/// A new directory in `base` whose canonical path is [`ROOT_LENGTH`]
/// bytes long. Messages that name the project's files wrap by their
/// length, so the tests make theirs as long.
fn padded(base: &Path) -> Result<PathBuf> {
    let base = canonical(base)?;
    let pad = ROOT_LENGTH
        .checked_sub(base.len() + 1)
        .filter(|&n| n > 0)
        .with_context(|| format!("{base} is too long to pad to {ROOT_LENGTH} bytes"))?;
    let dir = Path::new(&base).join("p".repeat(pad));
    fs::create_dir_all(&dir)?;
    Ok(dir)
}

fn canonical(dir: &Path) -> Result<String> {
    let path: PathBuf = fs::canonicalize(dir)?;
    path.to_str()
        .map(str::to_owned)
        .context("a scratch path that isn't UTF-8")
}

/// Stores each package's `elm.json` at `dir/<author>/<project>/<version>`.
fn store_packages(dir: &Path, pinned: &[packages::Package]) -> Result<()> {
    if dir.exists() {
        fs::remove_dir_all(dir)?;
    }
    let corpus = corpus_dir()?;
    for package in pinned {
        let to = dir.join(&package.name).join(&package.version);
        fs::create_dir_all(&to)?;
        fs::copy(
            packages::package_dir(&corpus, package).join("elm.json"),
            to.join("elm.json"),
        )
        .with_context(|| format!("{} {}", package.name, package.version))?;
    }
    Ok(())
}
