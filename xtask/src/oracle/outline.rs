//! `cargo xtask oracle outline`: what each pinned elm reports for each
//! `elm.json` fixture, stored for the outline test.
//!
//! elm runs `make` with no modules in a project holding only the fixture
//! and an empty `src/`, so the first thing it does is read `elm.json`
//! (`Details.load`). A report about the file is summarized as its title
//! and the code excerpt's shape: the rows shown, and the underline or the
//! rows marked with `>`. Any other outcome means elm read the outline and
//! moved on.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use anyhow::{Context, Result, bail, ensure};
use serde::Deserialize;

use super::{binary_path, cache_dir};
use crate::corpus::compat::{self, Version};
use crate::corpus::parallel_on;
use crate::references::References;

pub const FIXTURES: &str = "crates/project/tests/outline_fixtures";

pub const HEADER: &str = "# @generated by `cargo xtask oracle outline`; regenerate, never edit.";

/// Long enough to read any fixture many times over. upstream loops
/// forever on some decode errors (`Reporting/Error/Json.hs`,
/// `expectationToReport`), so this is how such a loop is told.
const TIMEOUT: Duration = Duration::from_secs(10);

/// The titles of reports about `elm.json` itself, before elm looks at
/// source directories or packages.
const TITLES: &[&str] = &[
    // Reporting/Error/Json.hs, parse errors.
    "EXPECTING A VALUE",
    "EXTRA COMMA",
    "EXPECTING COLON",
    "UNFINISHED OBJECT",
    "UNFINISHED ARRAY",
    "ENDLESS STRING",
    "UNEXPECTED CONTROL CHARACTER",
    "UNKNOWN ESCAPE",
    "BAD HEX ESCAPE",
    "UNEXPECTED ENCODING",
    "BAD NUMBER",
    "UNEXPECTED NUMBER",
    "JSON PROBLEM",
    // Reporting/Error/Json.hs, decode errors.
    "EXPECTING OBJECT",
    "EXPECTING ARRAY",
    "EXPECTING STRING",
    "EXPECTING BOOL",
    "EXPECTING INT",
    "MISSING FIELD",
    "EXPECTING PAIR",
    // Reporting/Exit.hs, toOutlineProblemReport and toOutlineReport.
    "UNEXPECTED TYPE",
    "INVALID PACKAGE NAME",
    "PROBLEM WITH VERSION",
    "PROBLEM WITH CONSTRAINT",
    "PROBLEM WITH MODULE NAME",
    "HEADER TOO LONG",
    "PROBLEM WITH DEPENDENCY NAME",
    "UNKNOWN LICENSE",
    "SUMMARY TOO LONG",
    "NO SOURCE DIRECTORIES",
    "MISSING DEPENDENCY",
];

pub fn run(root: &Path, refs: &References) -> Result<()> {
    let dir = root.join(FIXTURES);
    let mut fixtures: Vec<String> = fs::read_dir(&dir)
        .with_context(|| format!("reading {}", dir.display()))?
        .map(|entry| Ok(entry?.file_name().to_string_lossy().into_owned()))
        .collect::<Result<Vec<_>>>()?
        .into_iter()
        .filter_map(|name| name.strip_suffix(".json").map(str::to_owned))
        .collect();
    fixtures.sort();
    let elms: Vec<(Version, PathBuf)> = compat::compats(refs)?
        .into_iter()
        .map(|v| {
            let binary = refs
                .binary
                .iter()
                .find(|b| b.name == "elm" && b.version == v.to_string())
                .with_context(|| format!("elm {v} is not pinned"))?;
            let path = binary_path(binary)?;
            ensure!(
                path.exists(),
                "{} is missing; run `cargo xtask oracle fetch`",
                path.display()
            );
            Ok((v, path))
        })
        .collect::<Result<_>>()?;
    let sandboxes = cache_dir()?.join("sandboxes").join("outline");
    let jobs: Vec<(usize, &(Version, PathBuf))> = (0..fixtures.len())
        .flat_map(|i| elms.iter().map(move |elm| (i, elm)))
        .collect();
    let workers = std::thread::available_parallelism().map_or(1, |n| n.get());
    let results = parallel_on(workers, &jobs, |&(i, (version, elm))| {
        let name = &fixtures[i];
        let text = fs::read(dir.join(format!("{name}.json")))?;
        let project = sandboxes.join(version.to_string()).join(name);
        record(elm, &project, &text).with_context(|| format!("elm {version} on {name}"))
    });
    let mut out = format!("{HEADER}\nfixture");
    for (version, _) in &elms {
        write!(out, "\telm {version}")?;
    }
    out.push('\n');
    let mut results = results.into_iter();
    for name in &fixtures {
        out.push_str(name);
        for _ in &elms {
            write!(out, "\t{}", results.next().expect("a result")?)?;
        }
        out.push('\n');
    }
    fs::write(dir.join("oracle.tsv"), out)?;
    println!(
        "recorded {} fixtures for {} elms",
        fixtures.len(),
        elms.len()
    );
    Ok(())
}

/// Runs `elm` on a fresh project whose `elm.json` is `text`.
fn record(elm: &Path, project: &Path, text: &[u8]) -> Result<String> {
    if project.exists() {
        fs::remove_dir_all(project)?;
    }
    fs::create_dir_all(project.join("src"))?;
    fs::create_dir_all(project.join("home"))?;
    fs::write(project.join("elm.json"), text)?;
    let (stdout, stderr) = (project.join("stdout"), project.join("stderr"));
    let mut child = Command::new(elm)
        // A loop allocates without bound; the cap ends it early.
        .args(["make", "--report=json", "+RTS", "-N1", "-M512m", "-RTS"])
        .current_dir(project)
        .env("ELM_HOME", project.join("home"))
        .env("HTTPS_PROXY", "http://127.0.0.1:9")
        .env("HTTP_PROXY", "http://127.0.0.1:9")
        .env_remove("NO_PROXY")
        .stdin(Stdio::null())
        .stdout(fs::File::create(&stdout)?)
        .stderr(fs::File::create(&stderr)?)
        .spawn()
        .with_context(|| format!("running {}", elm.display()))?;
    let started = Instant::now();
    let timed_out = loop {
        if child.try_wait()?.is_some() {
            break false;
        }
        if started.elapsed() > TIMEOUT {
            child.kill()?;
            child.wait()?;
            break true;
        }
        std::thread::sleep(Duration::from_millis(5));
    };
    let (stdout, stderr) = (fs::read(stdout)?, fs::read(stderr)?);
    let errors = String::from_utf8_lossy(&stderr);
    if timed_out || errors.contains("Heap exhausted") || errors.contains("<<loop>>") {
        return Ok("loop".to_owned());
    }
    match [&stderr, &stdout].into_iter().find(|o| o.starts_with(b"{")) {
        Some(json) => summarize(json),
        // GHC's report of an uncaught exception.
        None if errors.starts_with("elm: ") => Ok("crash".to_owned()),
        None => Ok("accepted".to_owned()),
    }
}

#[derive(Deserialize)]
#[serde(tag = "type", rename_all = "kebab-case")]
enum Report {
    Error {
        path: Option<String>,
        title: String,
        message: Vec<Chunk>,
    },
    CompileErrors {},
}

#[derive(Deserialize)]
#[serde(untagged)]
enum Chunk {
    Plain(String),
    Styled { string: String },
}

/// The title and the excerpt's shape, or `accepted` for a report that
/// isn't about `elm.json`.
fn summarize(json: &[u8]) -> Result<String> {
    // elm copies control characters from the source into its messages
    // unescaped, which JSON forbids, and 0.19.1 writes the bytes of a
    // character that isn't one; newlines elm writes are escaped.
    let json: Vec<u8> = json
        .iter()
        .map(|&b| if b < 0x20 { b' ' } else { b })
        .collect();
    let json = String::from_utf8_lossy(&json);
    let report: Report = serde_json::from_str(&json).context("parsing elm's report")?;
    let Report::Error {
        path,
        title,
        message,
    } = report
    else {
        return Ok("accepted".to_owned());
    };
    if path.as_deref() != Some("elm.json") || !TITLES.contains(&title.as_str()) {
        return Ok("accepted".to_owned());
    }
    let text: String = message
        .iter()
        .map(|chunk| match chunk {
            Chunk::Plain(s) | Chunk::Styled { string: s } => s.as_str(),
        })
        .collect();
    Ok(format!("{title} {}", excerpt(&text)?))
}

/// `Render/Code.hs`'s `render`, read back: `rows A-B`, then `^C+W` for an
/// underline at column C, W wide, or `>C-D` for the rows marked.
fn excerpt(text: &str) -> Result<String> {
    let mut rows = Vec::new();
    let mut marked = Vec::new();
    let mut width = 0;
    let mut underline = None;
    for line in text.lines() {
        let trimmed = line.trim_start();
        let digits = trimmed.bytes().take_while(u8::is_ascii_digit).count();
        if digits > 0 && trimmed.as_bytes().get(digits) == Some(&b'|') {
            let row: u32 = trimmed[..digits].parse()?;
            rows.push(row);
            if trimmed.as_bytes().get(digits + 1) == Some(&b'>') {
                marked.push(row);
            }
            width = line.len() - trimmed.len() + digits;
        } else if !trimmed.is_empty() && trimmed.bytes().all(|b| b == b'^') && underline.is_none() {
            let spaces = line.len() - trimmed.len();
            underline = Some((spaces, trimmed.len()));
        }
    }
    let (Some(first), Some(last)) = (rows.first(), rows.last()) else {
        return Ok("rows none".to_owned());
    };
    let mut shape = format!("rows {first}-{last}");
    if let Some((spaces, carets)) = underline {
        ensure!(marked.is_empty(), "both an underline and marked rows");
        // `c1 + width + 2` spaces for a zero-based column.
        let col = spaces
            .checked_sub(width + 1)
            .context("an underline left of the code")?;
        write!(shape, " ^{col}+{carets}")?;
    } else if let (Some(a), Some(b)) = (marked.first(), marked.last()) {
        if marked.len() as u32 != b - a + 1 {
            bail!("marked rows are not contiguous: {marked:?}");
        }
        write!(shape, " >{a}-{b}")?;
    }
    Ok(shape)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn underlines_are_one_based_columns() {
        let text = "I ran into trouble:\n\n 9|    \"x\": 1\n10|    \"y\" 2\n          ^\nTry this.";
        assert_eq!(excerpt(text).unwrap(), "rows 9-10 ^7+1");
    }

    #[test]
    fn marked_rows() {
        let text = "Here:\n\n1| {\n2|>    \"a\": [\n3|>    ]\n4| }\nMore.";
        assert_eq!(excerpt(text).unwrap(), "rows 1-4 >2-3");
    }

    #[test]
    fn reports_about_other_things_are_acceptance() {
        let report = br#"{"type":"error","path":"elm.json","title":"MISSING SOURCE DIRECTORY","message":[]}"#;
        assert_eq!(summarize(report).unwrap(), "accepted");
        let report = br#"{"type":"error","path":"elm.json","title":"NO SOURCE DIRECTORIES","message":["Here:\n\n3|   \"source-directories\": []\n",{"bold":false,"underline":false,"color":"RED","string":"                         ^^"},"\nMore."]}"#;
        assert_eq!(
            summarize(report).unwrap(),
            "NO SOURCE DIRECTORIES rows 3-3 ^23+2"
        );
    }
}
