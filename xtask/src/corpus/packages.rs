//! Every package in the Elm registry at its latest version, pinned by the
//! registry's own hash: the SHA-1 of the zipball `endpoint.json` names.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail, ensure};
use serde::Deserialize;

use super::{corpus_dir, downloading};
use crate::download;
use crate::oracle::remove_tree;

const REGISTRY: &str = "https://package.elm-lang.org";
const FILE: &str = "corpus/packages.toml";
/// Written into a package's directory once its zipball has been verified.
pub(crate) const STAMP: &str = ".nomi-sha1";

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct Packages {
    #[serde(default)]
    pub packages: Vec<Package>,
    /// Listed by the registry, but its zipball cannot be fetched or does not
    /// match the registry's hash.
    #[serde(default)]
    pub unavailable: BTreeMap<String, String>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct Package {
    pub name: String,
    pub version: String,
    pub sha1: String,
}

pub(crate) fn load(root: &Path) -> Result<Packages> {
    let path = root.join(FILE);
    let text = fs::read_to_string(&path).with_context(|| format!("reading {FILE}"))?;
    toml::from_str(&text).with_context(|| format!("parsing {FILE}"))
}

pub(crate) fn package_dir(corpus: &Path, package: &Package) -> PathBuf {
    corpus
        .join("packages")
        .join(&package.name)
        .join(&package.version)
}

/// [`package_dir`], once the package is fetched and verified.
pub(crate) fn fetched_dir(corpus: &Path, package: &Package) -> Result<PathBuf> {
    let dir = package_dir(corpus, package);
    ensure!(
        download::stamped(&dir.join(STAMP), &package.sha1),
        "{} {} is not fetched; run `cargo xtask corpus fetch`",
        package.name,
        package.version
    );
    Ok(dir)
}

/// Re-pins the corpus from the live registry: every package's latest
/// version, kept only if its zipball downloads and matches the registry.
pub(crate) fn pin(root: &Path) -> Result<()> {
    #[derive(Deserialize)]
    struct Listed {
        name: String,
        version: String,
    }
    #[derive(Deserialize)]
    struct Endpoint {
        hash: String,
    }
    let listed: Vec<Listed> =
        serde_json::from_slice(&download::get(&format!("{REGISTRY}/search.json"))?)
            .context("parsing search.json")?;
    eprintln!("  {} packages listed; reading endpoints", listed.len());
    let corpus = corpus_dir()?;
    let results = downloading(&listed, |l| -> Result<Package> {
        let url = format!("{REGISTRY}/packages/{}/{}/endpoint.json", l.name, l.version);
        let endpoint: Endpoint = serde_json::from_slice(&download::get_quiet(&url)?)
            .with_context(|| format!("parsing {url}"))?;
        let package = Package {
            name: l.name.clone(),
            version: l.version.clone(),
            sha1: endpoint.hash,
        };
        fetch_one(&corpus, &package)?;
        Ok(package)
    });
    let mut packages = Vec::new();
    let mut unavailable = BTreeMap::new();
    for (l, result) in listed.iter().zip(results) {
        match result {
            Ok(p) => packages.push(p),
            Err(e) => {
                unavailable.insert(l.name.clone(), format!("{} {}", l.version, reason(&e)));
            }
        }
    }
    packages.sort_by(|a, b| a.name.cmp(&b.name));
    let text = render(&packages, &unavailable);
    fs::write(root.join(FILE), text).with_context(|| format!("writing {FILE}"))?;
    eprintln!(
        "  pinned {} packages, {} unavailable",
        packages.len(),
        unavailable.len()
    );
    Ok(())
}

/// A short, stable reason for the pin file.
fn reason(error: &anyhow::Error) -> String {
    if error.downcast_ref::<download::HashMismatch>().is_some() {
        return "zipball does not match the registry's hash".to_string();
    }
    let root = error.root_cause().to_string();
    root.lines().next().unwrap_or("").to_string()
}

fn render(packages: &[Package], unavailable: &BTreeMap<String, String>) -> String {
    let mut out = String::from(
        "# @generated by `cargo xtask corpus pin` from the Elm registry's\n\
         # search.json; edit by re-pinning. Each package is its latest version,\n\
         # pinned by the registry's SHA-1 of its zipball.\n",
    );
    for p in packages {
        let _ = write!(
            out,
            "\n[[packages]]\nname = {:?}\nversion = {:?}\nsha1 = {:?}\n",
            p.name, p.version, p.sha1
        );
    }
    out.push_str("\n[unavailable]\n");
    for (name, reason) in unavailable {
        let _ = writeln!(out, "{name:?} = {reason:?}");
    }
    out
}

/// Downloads and unpacks every pinned package that is not already verified.
pub(crate) fn fetch(root: &Path) -> Result<()> {
    let pins = load(root)?;
    let corpus = corpus_dir()?;
    let results = downloading(&pins.packages, |p| {
        fetch_one(&corpus, p).with_context(|| format!("{} {}", p.name, p.version))
    });
    let failures: Vec<String> = results
        .into_iter()
        .filter_map(|r| r.err().map(|e| format!("{e:#}")))
        .collect();
    if !failures.is_empty() {
        bail!(
            "{} package(s) failed:\n  {}",
            failures.len(),
            failures.join("\n  ")
        );
    }
    eprintln!("  {} packages verified", pins.packages.len());
    Ok(())
}

fn fetch_one(corpus: &Path, package: &Package) -> Result<()> {
    let dir = package_dir(corpus, package);
    let stamp = dir.join(STAMP);
    if download::stamped(&stamp, &package.sha1) && !has_case_variants(&dir)? {
        return Ok(());
    }
    let url = download::zipball(&package.name, &package.version);
    let zip = download::get_quiet(&url)?;
    download::verify(&url, &package.sha1, &nomi_registry::store::sha1(&zip))?;
    remove_tree(&dir)?;
    unzip_stripped(&zip, &dir)?;
    fs::write(&stamp, &package.sha1)?;
    Ok(())
}

/// Unpacks a GitHub zipball into `dir`, dropping its single top directory.
///
/// Names that differ only in case are one name, spelled as the archive
/// first spells it, as a case-insensitive filesystem (macOS's, Windows')
/// unpacks them; so the tree, and the tables keyed by its paths, are the
/// same on every machine. jxxcarlson/meenylatex 14.1.1 has `Demo/src/*.elm`
/// and `demo/src/Main.elm`, which a case-sensitive one would keep apart.
fn unzip_stripped(bytes: &[u8], dir: &Path) -> Result<()> {
    let mut archive = zip::ZipArchive::new(io::Cursor::new(bytes)).context("reading zip")?;
    // Each path unpacked so far, folded, to its first spelling.
    let mut spelled: HashMap<String, PathBuf> = HashMap::new();
    for i in 0..archive.len() {
        let mut entry = archive.by_index(i)?;
        let Some(path) = entry.enclosed_name() else {
            bail!("zip entry {:?} escapes its directory", entry.name());
        };
        let mut relative = PathBuf::new();
        for component in path.components().skip(1) {
            let next = relative.join(component);
            let folded = next.to_string_lossy().to_lowercase();
            relative = spelled.entry(folded).or_insert(next).clone();
        }
        if relative.as_os_str().is_empty() {
            continue;
        }
        let target = dir.join(relative);
        if entry.is_dir() {
            fs::create_dir_all(&target)?;
        } else if entry.is_file() {
            fs::create_dir_all(target.parent().expect("a file in a directory"))?;
            io::copy(&mut entry, &mut fs::File::create(&target)?)?;
        }
    }
    Ok(())
}

/// Whether two names in one directory under `dir` differ only in case,
/// as a package unpacked before [`unzip_stripped`] folded them can have.
fn has_case_variants(dir: &Path) -> Result<bool> {
    let mut stack = vec![dir.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let mut folded = HashSet::new();
        for entry in fs::read_dir(&dir)? {
            let entry = entry?;
            if !folded.insert(entry.file_name().to_string_lossy().to_lowercase()) {
                return Ok(true);
            }
            if entry.file_type()?.is_dir() {
                stack.push(entry.path());
            }
        }
    }
    Ok(false)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rendered_pins_parse_back() {
        let packages = vec![Package {
            name: "elm/core".into(),
            version: "1.0.5".into(),
            sha1: "9288a7574b778b4ebc6557d504a0b16c09daab43".into(),
        }];
        let unavailable = BTreeMap::from([("a/gone".into(), "1.0.0 GET failed: 404".into())]);
        let parsed: Packages = toml::from_str(&render(&packages, &unavailable)).unwrap();
        assert_eq!(parsed.packages[0].name, "elm/core");
        assert_eq!(parsed.unavailable["a/gone"], "1.0.0 GET failed: 404");
    }

    #[test]
    fn reasons_are_short() {
        let mismatch = download::verify("url", "aa", "bb").unwrap_err();
        assert_eq!(
            reason(&mismatch.context("fetching")),
            "zipball does not match the registry's hash"
        );
        let missing = anyhow::anyhow!("http status: 404").context("GET url");
        assert_eq!(reason(&missing), "http status: 404");
    }

    #[test]
    fn zipball_top_directory_is_stripped() {
        let mut zip = zip::ZipWriter::new(io::Cursor::new(Vec::new()));
        let options = zip::write::SimpleFileOptions::default();
        zip.add_directory("elm-core-abc/", options).unwrap();
        zip.start_file("elm-core-abc/src/Basics.elm", options)
            .unwrap();
        io::Write::write_all(&mut zip, b"module Basics").unwrap();
        let bytes = zip.finish().unwrap().into_inner();
        let dir = tempfile::tempdir().unwrap();
        unzip_stripped(&bytes, dir.path()).unwrap();
        assert_eq!(
            fs::read_to_string(dir.path().join("src/Basics.elm")).unwrap(),
            "module Basics"
        );
    }

    #[test]
    fn names_differing_in_case_unpack_as_the_first_spelling() {
        let mut zip = zip::ZipWriter::new(io::Cursor::new(Vec::new()));
        let options = zip::write::SimpleFileOptions::default();
        for (name, text) in [
            ("top/Demo/src/Style.elm", "style"),
            ("top/demo/src/Main.elm", "main"),
            ("top/demo/SRC/main.elm", "last"),
        ] {
            zip.start_file(name, options).unwrap();
            io::Write::write_all(&mut zip, text.as_bytes()).unwrap();
        }
        let bytes = zip.finish().unwrap().into_inner();
        let temp = tempfile::tempdir().unwrap();
        let dir = temp.path();
        unzip_stripped(&bytes, dir).unwrap();
        assert_eq!(
            nomi_testkit::files_below(dir).unwrap(),
            ["Demo/src/Main.elm", "Demo/src/Style.elm"]
        );
        assert_eq!(
            fs::read_to_string(dir.join("Demo/src/Main.elm")).unwrap(),
            "last"
        );
        assert!(!has_case_variants(dir).unwrap());
        // Only a filesystem that tells cases apart, unlike macOS's and
        // Windows' by default, can hold both spellings.
        match fs::create_dir(dir.join("demo")) {
            Ok(()) => assert!(has_case_variants(dir).unwrap()),
            Err(e) => assert_eq!(e.kind(), io::ErrorKind::AlreadyExists),
        }
    }
}
