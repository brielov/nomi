//! `cargo xtask corpus fixtures`: the elm/* packages tier 1 compiles
//! against (plan 5.3), copied from the corpus, whose zipballs were
//! checked against the registry's hashes when fetched. Each copy keeps
//! `elm.json`, `LICENSE` and `src/`; `manifest.toml` names its release,
//! the registry's hash and a digest of the files, which the compiler's
//! tests check.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, ensure};

use super::{corpus_dir, files_below, packages, tree_digest};

pub const DIR: &str = "crates/compiler/tests/packages";

/// The packages the corpus apps build with that tier 1 needs, and the
/// test framework the language server finds tests with.
const PACKAGES: [&str; 12] = [
    "elm/core",
    "elm/json",
    "elm/html",
    "elm/browser",
    "elm/url",
    "elm/virtual-dom",
    "elm/time",
    "elm/http",
    "elm/bytes",
    "elm/file",
    "elm/random",
    "elm-explorations/test",
];

pub fn run(root: &Path) -> Result<()> {
    let corpus = corpus_dir()?;
    let pins = packages::load(root)?;
    let dir = root.join(DIR);
    if dir.exists() {
        fs::remove_dir_all(&dir)?;
    }
    let mut manifest =
        String::from("# @generated by `cargo xtask corpus fixtures`; regenerate, never edit.\n");
    for name in PACKAGES {
        let pin = (pins.packages.iter())
            .find(|p| p.name == name)
            .with_context(|| format!("the corpus doesn't pin {name}"))?;
        let from = packages::package_dir(&corpus, pin);
        ensure!(
            fs::read_to_string(from.join(packages::STAMP))
                .ok()
                .as_deref()
                == Some(&pin.sha1),
            "{name} {} is not fetched; run `cargo xtask corpus fetch`",
            pin.version
        );
        let to = dir.join(name).join(&pin.version);
        for file in ["elm.json", "LICENSE"] {
            copy(&from.join(file), &to.join(file))?;
        }
        for file in files_below(&from.join("src"))? {
            copy(&from.join("src").join(&file), &to.join("src").join(&file))?;
        }
        let files = files_below(&to)?;
        writeln!(
            manifest,
            "\n[[package]]\nname = \"{name}\"\nversion = \"{}\"\nsha1 = \"{}\"\nfiles = {}\ndigest = \"{}\"",
            pin.version,
            pin.sha1,
            files.len(),
            tree_digest(&to, &files)?
        )?;
    }
    fs::write(dir.join("manifest.toml"), manifest)?;
    println!("copied {} packages into {DIR}", PACKAGES.len());
    Ok(())
}

fn copy(from: &Path, to: &Path) -> Result<()> {
    fs::create_dir_all(to.parent().expect("a file in a directory"))?;
    fs::copy(from, to).with_context(|| format!("copying {}", from.display()))?;
    Ok(())
}
