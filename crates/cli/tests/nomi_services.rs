//! The tier-2 suites `cargo xtask services` runs, each against a server in
//! a container whose URL it gives in `NOMI_SERVICE_<NAME>`: nomi/sql's
//! shared tests (the `sql` suite's `SqlTest`) and its server tests
//! (`ServerTest`) on Postgres and on MySQL, with a `Database` module of the
//! server's own in place of SQLite's. Built only with the `services`
//! feature, so tier 1 lints these and runs none.

#[path = "support/website.rs"]
pub mod website;

use std::fs;
use std::path::Path;

use website::offline;

/// The server's URL, which `cargo xtask services` gives.
fn url(service: &str) -> String {
    let var = format!("NOMI_SERVICE_{}", service.to_uppercase());
    std::env::var(&var).unwrap_or_else(|_| {
        panic!("{var} isn't set: these tests run under `cargo xtask services {service}`")
    })
}

/// How the shared tests reach one kind of server.
struct Server {
    /// `Database.Kind`'s constructor.
    kind: &'static str,
    /// A placeholder as the server writes one: `?`, or `$n` on Postgres.
    dollars: bool,
    auto_id: &'static str,
    blob: &'static str,
    /// What follows the tables dropped, as Postgres drops what depends on
    /// them.
    cascade: &'static str,
}

const POSTGRES: Server = Server {
    kind: "Postgres",
    dollars: true,
    auto_id: "integer generated by default as identity primary key",
    blob: "bytea",
    cascade: " cascade",
};

const MYSQL: Server = Server {
    kind: "Mysql",
    dollars: false,
    auto_id: "integer auto_increment primary key",
    blob: "blob",
    cascade: "",
};

/// The `Database` module for `server` at `url`: each test's database is a
/// new pool, the tables of the tests before it dropped.
fn database(server: &Server, url: &str) -> String {
    let sql = if server.dollars {
        "String.split \"?\" statement\n        |> List.indexedMap (\\i part -> if i == 0 then part else \"$\" ++ String.fromInt i ++ part)\n        |> String.concat"
    } else {
        "statement"
    };
    format!(
        r#"module Database exposing (Kind(..), kind, url, fresh, sql, autoId, blobType)

import Nomi.Net exposing (Net)
import Nomi.Sql as Sql exposing (Db)
import Task exposing (Task)


type Kind
    = Sqlite
    | Postgres
    | Mysql


kind : Kind
kind =
    {kind}


url : String
url =
    "{url}"


fresh : Net -> Task Sql.Error Db
fresh net =
    case Sql.config url of
        Ok config ->
            Sql.connect config net
                |> Task.andThen (\db -> Sql.execute "drop table if exists items, lists, todos, big, kinds, a, b{cascade}" [] db |> Task.map (\_ -> db))

        Err why ->
            Task.fail (Sql.Unreachable why)


sql : String -> String
sql statement =
    {sql}


autoId : String
autoId =
    "{auto_id}"


blobType : String
blobType =
    "{blob}"
"#,
        kind = server.kind,
        cascade = server.cascade,
        auto_id = server.auto_id,
        blob = server.blob,
    )
}

/// The `sql` suite's shared tests and `services/ServerTest.elm` against
/// `server` at `url`, one test at a time, as they share its tables.
fn sql_suite_passes(server: &Server, url: &str) {
    nomi_testkit::require_bun();
    let work = tempfile::tempdir().unwrap();
    let root = fs::canonicalize(work.path()).unwrap();
    let suite = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/nomi_suites/sql");
    nomi_testkit::copy_tree(&suite, &root, |_| true).unwrap();
    fs::remove_file(root.join("tests/SqliteTest.elm")).unwrap();
    fs::rename(
        root.join("services/ServerTest.elm"),
        root.join("tests/ServerTest.elm"),
    )
    .unwrap();
    fs::write(root.join("src/Database.elm"), database(server, url)).unwrap();
    let cache = website::fixture_cache();
    let tested = offline(Path::new(env!("CARGO_BIN_EXE_nomi")), cache.path())
        .current_dir(&root)
        .args(["test", "--offline", "--no-color", "--workers", "1"])
        .args(["--seed", "1", "--fuzz", "500"])
        .output()
        .unwrap();
    let out = String::from_utf8_lossy(&tested.stdout);
    assert_eq!(tested.status.code(), Some(0), "{out}{tested:?}");
    assert!(out.contains("Failed:   0\n"), "{out}");
    assert!(!out.contains("Passed:   0\n"), "{out}");
}

mod postgres {
    #[test]
    fn the_sql_suite_passes() {
        super::sql_suite_passes(&super::POSTGRES, &super::url("postgres"));
    }
}

mod mysql {
    #[test]
    fn the_sql_suite_passes() {
        super::sql_suite_passes(&super::MYSQL, &super::url("mysql"));
    }
}
